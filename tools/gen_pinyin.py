#!/usr/bin/env python3
"""
Generate app/js/pinyin-data.js: a compact pinyin -> candidate table for the on-screen IME.

Sources: jieba's dict.txt (word + frequency) and pypinyin (word -> pinyin without tones).
Output format (ES5, loaded as a global):
  var PINYIN_DATA = { "lan": ["兰","蓝","烂",...], "lanxiang": ["兰香", ...], ... }
Keys are full pinyin strings with syllables concatenated (no separators), so the IME
can look up the whole buffer ("lanxiang") and progressively shorter prefixes.
Also includes an initials index ("lx" -> words) for abbreviation input.
"""
import json
import os
import re
import sys

import jieba
from pypinyin import lazy_pinyin, Style

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "js", "pinyin-data.js")

MAX_WORD_LEN = 4
TOP_CHARS = 3500            # single characters kept (by frequency)
TOP_WORDS = 20000           # multi-char words kept (by frequency)
CANDS_PER_KEY = 12          # candidates per pinyin key
CANDS_PER_INITIALS = 10     # candidates per initials key (e.g. "lx")

HAN = re.compile(r"^[\u4e00-\u9fff]+$")


def load_dict():
    path = os.path.join(os.path.dirname(jieba.__file__), "dict.txt")
    chars, words = [], []
    # extra vocabulary: film/TV titles that the user is likely to type (boosted to top)
    extra = os.path.join(ROOT, "tools", "titles.txt")
    if os.path.exists(extra):
        with open(extra, encoding="utf-8") as f:
            for line in f:
                w = line.strip()
                if w and HAN.match(w) and len(w) <= 8:
                    words.append((w, 10 ** 9))
    with open(path, encoding="utf-8") as f:
        for line in f:
            parts = line.split()
            if len(parts) < 2 or not HAN.match(parts[0]):
                continue
            w, freq = parts[0], int(parts[1])
            if len(w) == 1:
                chars.append((w, freq))
            elif len(w) <= MAX_WORD_LEN:
                words.append((w, freq))
    # keep extra titles even if longer than MAX_WORD_LEN
    chars.sort(key=lambda x: -x[1])
    words.sort(key=lambda x: -x[1])
    return chars[:TOP_CHARS], words[:TOP_WORDS]


def main():
    chars, words = load_dict()
    full = {}       # pinyin -> [(word, freq)]
    initials = {}   # initials -> [(word, freq)]

    def add(table, key, w, freq):
        table.setdefault(key, []).append((w, freq))

    for w, freq in chars:
        # heteronyms: index a char under every reading
        for py in set(p[0] for p in __import__("pypinyin").pinyin(w, style=Style.NORMAL, heteronym=True)):
            add(full, py, w, freq)
    for w, freq in words:
        syl = lazy_pinyin(w, style=Style.NORMAL)
        add(full, "".join(syl), w, freq)
        add(initials, "".join(s[0] for s in syl), w, freq)

    def finish(table, n):
        out = {}
        for k, lst in table.items():
            lst.sort(key=lambda x: -x[1])
            seen, res = set(), []
            for w, _ in lst:
                if w not in seen:
                    seen.add(w)
                    res.append(w)
                if len(res) >= n:
                    break
            out[k] = res
        return out

    full_o = finish(full, CANDS_PER_KEY)
    init_o = {k: v for k, v in finish(initials, CANDS_PER_INITIALS).items() if len(k) >= 2}

    js = "/* generated by tools/gen_pinyin.py — do not edit. ES5 global. */\n"
    js += "var PINYIN_DATA = " + json.dumps(full_o, ensure_ascii=False, separators=(",", ":")) + ";\n"
    js += "var PINYIN_INITIALS = " + json.dumps(init_o, ensure_ascii=False, separators=(",", ":")) + ";\n"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)
    print("keys: full=%d initials=%d  size=%d KB -> %s" % (len(full_o), len(init_o), os.path.getsize(OUT) // 1024, OUT))
    for k in ("lan", "lanxiang", "lxrg", "liulang", "xibu", "ni"):
        print(" ", k, "->", (full_o.get(k) or init_o.get(k) or [])[:8])


if __name__ == "__main__":
    sys.exit(main())
